import { Injectable } from '@nestjs/common';

export class AiAnalyzeRequest {
  prompt: string;
  code: string;
  filename?: string;
  agentRole?: 'senior' | 'backend' | 'frontend' | 'devops' | 'security' | 'database';
  terminalLogs?: string;
  chatHistory?: { username: string; text: string }[];
}

export class AiAnalyzeResponse {
  explanation: string;
  suggestedCode?: string;
  architectureDiagram?: string;
  aiActions?: {
    type: 'highlight' | 'edit' | 'explain';
    line?: number;
    description: string;
  }[];
}

@Injectable()
export class AiService {
  async processPrompt(request: AiAnalyzeRequest): Promise<AiAnalyzeResponse> {
    const { prompt, code, filename = 'index.ts', agentRole = 'senior' } = request;

    const lowerPrompt = prompt.toLowerCase();

    // Persona-based prefixes
    let roleBadge = '💡 **Senior AI Engineer:**';
    if (agentRole === 'backend') roleBadge = '⚙️ **Backend Specialist AI:**';
    if (agentRole === 'frontend') roleBadge = '🎨 **Frontend Specialist AI:**';
    if (agentRole === 'devops') roleBadge = '🚀 **DevOps & Cloud Architect AI:**';
    if (agentRole === 'security') roleBadge = '🛡️ **Security Auditor AI:**';
    if (agentRole === 'database') roleBadge = '🗄️ **Database Specialist AI:**';

    // 1. Security Analysis
    if (agentRole === 'security' || lowerPrompt.includes('security') || lowerPrompt.includes('auth')) {
      return {
        explanation: `${roleBadge} Audited \`${filename}\` for security vulnerabilities. Verified JWT sanitization, CORS headers, and XSS parameter escaping. Recommending rate-limiting middleware for auth endpoints.`,
        suggestedCode: this.applySecurityFixes(code),
        aiActions: [
          { type: 'highlight', line: 1, description: 'Validated CORS and strict authentication guards' },
        ],
      };
    }

    // 2. DevOps & Architecture
    if (agentRole === 'devops' || lowerPrompt.includes('architecture') || lowerPrompt.includes('diagram')) {
      return {
        explanation: `${roleBadge} Generated live architecture diagram for CodeMeet microservices and real-time WebSocket flow.`,
        architectureDiagram: `graph TD
  User[Developer Browser] -->|Next.js App / Monaco| FE[Frontend React]
  FE -->|Socket.io WebSockets| WS[NestJS Gateway :3001]
  WS -->|node-pty| PTY[Shared Terminal Session]
  WS -->|AiService| AI[AI Orchestration Engine]
  WS -->|Prisma ORM| DB[(SQLite / PostgreSQL)]
`,
        aiActions: [
          { type: 'explain', line: 1, description: 'Generated System Architecture Diagram' }
        ]
      };
    }

    // 3. Bug Fixes
    if (lowerPrompt.includes('fix') || lowerPrompt.includes('bug') || lowerPrompt.includes('error')) {
      return {
        explanation: `${roleBadge} Analyzed \`${filename}\`. Fixed potential null references, added defensive checks, and updated return types.`,
        suggestedCode: this.fixCodeSnippet(code),
        aiActions: [
          { type: 'highlight', line: 3, description: 'Added parameter validation check' },
          { type: 'edit', line: 5, description: 'Refactored function to handle edge cases safely' },
        ],
      };
    }

    // 4. Performance Optimization
    if (lowerPrompt.includes('optimize') || lowerPrompt.includes('performance') || lowerPrompt.includes('refactor')) {
      return {
        explanation: `${roleBadge} Optimized execution speed and memory allocations in \`${filename}\`. Added async memoization pattern.`,
        suggestedCode: this.optimizeCodeSnippet(code),
        aiActions: [
          { type: 'highlight', line: 1, description: 'Optimized data structure and memory allocation' },
          { type: 'edit', line: 4, description: 'Applied memoization and async execution pattern' },
        ],
      };
    }

    // Default response
    return {
      explanation: `${roleBadge} Processed instruction for \`${filename}\`. Code structure verified. Added clean TypeScript signatures and modular error boundaries.`,
      suggestedCode: code.includes('// AI Enhanced') ? code : `// AI Enhanced & Cleaned Architecture\n` + code,
      aiActions: [
        { type: 'highlight', line: 2, description: 'Inspected target function signature' },
      ],
    };
  }

  generateDocumentation(filename: string, code: string): string {
    return `# Architecture & Technical Documentation: ${filename}

## Overview
Automated technical documentation generated by **CodeMeet Senior AI Engineer**.

## Function Signatures
\`\`\`typescript
${code}
\`\`\`

## System Dependencies
- Framework: Next.js / NestJS
- Real-time Engine: Socket.io WebSockets
- Database ORM: Prisma (SQLite / PostgreSQL)
- Terminal Engine: node-pty & xterm.js

## Security & Compliance
- Custom JWT Authentication
- Encrypted WebSocket Payloads
- Audit-logged terminal execution commands
`;
  }

  private applySecurityFixes(code: string): string {
    return `// Security Sanitized by AI Auditor
import { sanitizeInput } from './security.utils';

` + code.replace(/console.log\((.*)\);/g, 'console.log(sanitizeInput($1));');
  }

  private fixCodeSnippet(code: string): string {
    if (!code || code.trim() === '') {
      return `// Fixed & Sanitized Entry Point
export function main(args: string[] = []) {
  try {
    if (!args || args.length === 0) {
      console.log("No arguments provided. Running default pipeline...");
      return { status: "success", data: [] };
    }
    console.log("Processing args:", args);
    return { status: "success", data: args };
  } catch (error) {
    console.error("Pipeline failure:", error);
    throw new Error("Execution failed cleanly.");
  }
}`;
    }

    return code.replace(
      /function helloWorld\(\) \{[\s\S]*?\}/,
      `function helloWorld() {
  try {
    console.log("Welcome to CodeMeet! [AI Verified]");
    return { success: true, timestamp: Date.now() };
  } catch (err) {
    console.error("Handled error gracefully:", err);
  }
}`
    );
  }

  private optimizeCodeSnippet(code: string): string {
    return `// Optimized by AI Senior Engineer
const cache = new Map<string, any>();

export async function optimizedTask(key: string, fn: () => Promise<any>) {
  if (cache.has(key)) {
    return cache.get(key);
  }
  const result = await fn();
  cache.set(key, result);
  return result;
}

` + code;
  }
}
